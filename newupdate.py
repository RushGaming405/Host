def process_approve_file(call):
    if call.from_user.id not in admin_ids:
        bot.answer_callback_query(call.id, "⚠️ Admin permissions required.", show_alert=True)
        return
    data_parts = call.data.split('_')
    if len(data_parts) < 4:
        bot.answer_callback_query(call.id, "❌ Invalid data.", show_alert=True)
        return
    try:
        user_id = int(data_parts[2])
    except ValueError:
        bot.answer_callback_query(call.id, "❌ Invalid user ID.", show_alert=True)
        return
    file_name = '_'.join(data_parts[3:])
    pending = pending_file_uploads.get(user_id, {}).get(file_name)
    if not pending:
        bot.answer_callback_query(call.id, "❌ Pending file not found. Ask user to re-upload.", show_alert=True)
        return
    user_folder = get_user_folder(user_id)
    file_path = os.path.join(user_folder, file_name)
    file_ext = os.path.splitext(file_name)[1].lower()
    try:
        with open(file_path, 'wb') as f:
            f.write(pending['content'])
        if file_ext == '.js':
            handle_js_file(file_path, user_id, user_folder, file_name, call.message)
        elif file_ext == '.py':
            handle_py_file(file_path, user_id, user_folder, file_name, call.message)
        else:
            raise ValueError("Unsupported pending file type")
        del pending_file_uploads[user_id][file_name]
        if not pending_file_uploads[user_id]:
            del pending_file_uploads[user_id]
        bot.answer_callback_query(call.id, "✅ Approved and started.")
        bot.edit_message_text(
            f"✅ File `{file_name}` approved by admin for user `{user_id}` and started.",
            call.message.chat.id, call.message.message_id, parse_mode='Markdown'
        )
        try:
            bot.send_message(user_id, f"✅ Your file `{file_name}` was approved by admin and has been started.")
        except Exception as e:
            logger.error(f"Failed to notify user {user_id}: {e}")
    except Exception as e:
        logger.error(f"Error processing approved file: {e}", exc_info=True)
        bot.answer_callback_query(call.id, "❌ Error starting approved file.", show_alert=True)

