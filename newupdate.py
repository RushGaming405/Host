def _watch_script_runtime(script_key):
    limit = int(SECURITY_CONFIG.get("max_script_runtime", 0) or 0)
    if limit <= 0:
        return
    while script_key in bot_scripts:
        info = bot_scripts.get(script_key)
        proc = info.get("process") if info else None
        if not proc or proc.poll() is not None:
            return
        started = info.get("start_time", datetime.now())
        elapsed = (datetime.now() - started).total_seconds()
        if elapsed > limit:
            logger.warning("Runtime limit reached for %s; terminating PID %s", script_key, proc.pid)
            try:
                kill_process_tree(info)
            except Exception:
                try:
                    proc.kill()
                except Exception:
                    pass
            return
        time.sleep(5)


