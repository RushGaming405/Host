def _python_security_scan(content):
    reasons = []
    if ast is None:
        return False, ["Python AST unavailable"]

    try:
        tree = ast.parse(content)
    except SyntaxError as e:
        return False, [f"Python syntax error: line {e.lineno}: {e.msg}"]

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".")[0]
                if root in SECURITY_CONFIG["blocked_imports"]:
                    reasons.append(f"blocked import: {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".")[0]
            if root in SECURITY_CONFIG["blocked_imports"]:
                reasons.append(f"blocked import: {node.module}")
        elif isinstance(node, ast.Call):
            if isinstance(node.func, ast.Name) and node.func.id in SECURITY_CONFIG["blocked_calls"]:
                reasons.append(f"dangerous call: {node.func.id}()")
            elif isinstance(node.func, ast.Attribute):
                chain = []
                cur = node.func
                while isinstance(cur, ast.Attribute):
                    chain.append(cur.attr)
                    cur = cur.value
                if isinstance(cur, ast.Name):
                    chain.append(cur.id)
                dotted = ".".join(reversed(chain))
                if dotted in {
                    "os.system", "os.popen", "os.execv", "os.execve",
                    "os.spawnv", "os.spawnve", "shutil.rmtree",
                    "subprocess.run", "subprocess.Popen", "subprocess.call",
                    "subprocess.check_output", "ctypes.CDLL",
                }:
                    reasons.append(f"dangerous call: {dotted}()")

    suspicious = [
        (r"curl\s+[^\\n|]*\|\s*(sh|bash)", "download-and-execute shell pipeline"),
        (r"wget\s+[^\\n|]*\|\s*(sh|bash)", "download-and-execute shell pipeline"),
        (r"/etc/(passwd|shadow)", "system credential file access"),
        (r"\.ssh/(id_rsa|authorized_keys|known_hosts)", "SSH credential access"),
        (r"rm\s+-rf\s+/(?:\s|$)", "destructive root deletion"),
        (r"(?:reverse|bind)\s*shell", "shell/backdoor indicator"),
        (r"base64\.b64decode\s*\(.*(?:exec|eval)", "obfuscated code execution"),
    ]
    for pattern, label in suspicious:
        if re.search(pattern, content, re.IGNORECASE):
            reasons.append(label)

    return (not reasons), reasons[:12]


def _js_security_scan(content):
    reasons = []
    patterns = [
        (r"\bchild_process\b", "child_process access"),
        (r"\bexec(?:File|Sync)?\s*\(", "process execution"),
        (r"\bspawn(?:Sync)?\s*\(", "process spawning"),
        (r"\brequire\s*\(\s*['\"](?:child_process|vm|cluster)['\"]", "dangerous Node module"),
        (r"\b(?:eval|Function)\s*\(", "dynamic code execution"),
        (r"(?:curl|wget)\s+[^\\n|]*\|\s*(?:sh|bash)", "download-and-execute shell pipeline"),
        (r"/etc/(?:passwd|shadow)", "system credential file access"),
        (r"\.ssh/(?:id_rsa|authorized_keys|known_hosts)", "SSH credential access"),
        (r"(?:reverse|bind)\s*shell", "shell/backdoor indicator"),
    ]
    for pattern, label in patterns:
        if re.search(pattern, content, re.IGNORECASE):
            reasons.append(label)
    try:
        if not content.strip():
            reasons.append("empty JavaScript file")
    except Exception:
        pass
    return (not reasons), reasons[:12]


def check_code_security(file_path, file_type):
    try:
        size = os.path.getsize(file_path)
        if size > SECURITY_CONFIG["max_file_size"]:
            return False, "file exceeds security size limit"

        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        if file_type.lower() == "py":
            safe, reasons = _python_security_scan(content)
        elif file_type.lower() == "js":
            safe, reasons = _js_security_scan(content)
        else:
            return False, f"unsupported executable type: {file_type}"

        if not safe:
            logger.warning("SECURITY HOLD %s: %s", file_path, reasons)
            return False, "; ".join(reasons)
        return True, "Static security scan passed"
    except Exception as e:
        logger.exception("Security scan failed")
        return False, f"security scanner error: {e}"


def _zip_member_is_safe(name):
    if not name or name.startswith(("/", "\\")):
        return False
    normalized = os.path.normpath(name.replace("\\", "/"))
    return normalized not in (".", "") and not normalized.startswith("../") and "/../" not in f"/{normalized}"


def scan_zip_security(zip_path):
    try:
        total_uncompressed = 0
        with zipfile.ZipFile(zip_path, "r") as zf:
            members = zf.infolist()
            if len(members) > SECURITY_CONFIG["max_archive_members"]:
                return False, f"archive has too many files ({len(members)})"

            for info in members:
                if not _zip_member_is_safe(info.filename):
                    return False, f"unsafe archive path: {info.filename}"

                mode = (info.external_attr >> 16) & 0o170000
                if mode == 0o120000:
                    return False, f"symlink entry is not allowed: {info.filename}"

                total_uncompressed += info.file_size
                if total_uncompressed > SECURITY_CONFIG["max_uncompressed_archive"]:
                    return False, "archive expands beyond 100 MB security limit"

                lower = info.filename.lower()
                if lower.endswith((".py", ".js")):
                    raw = zf.read(info)
                    if len(raw) > SECURITY_CONFIG["max_file_size"]:
                        return False, f"member too large: {info.filename}"
                    content = raw.decode("utf-8", errors="ignore")
                    if lower.endswith(".py"):
                        safe, reasons = _python_security_scan(content)
                    else:
                        safe, reasons = _js_security_scan(content)
                    if not safe:
                        return False, f"{info.filename}: " + "; ".join(reasons)

                if lower.endswith((".sh", ".bash", ".bat", ".cmd", ".ps1", ".exe", ".dll", ".so")):
                    return False, f"executable/installer file is not allowed: {info.filename}"

        return True, "Archive security scan passed"
    except zipfile.BadZipFile:
        return False, "invalid/corrupted ZIP archive"
    except Exception as e:
        logger.exception("ZIP security scan failed")
        return False, f"archive security scanner error: {e}"


