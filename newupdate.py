    while True:
        try:
            bot.infinity_polling(
                logger_level=logging.INFO,
                timeout=POLL_HTTP_TIMEOUT,
                long_polling_timeout=POLL_LONG_TIMEOUT,
                skip_pending=True,
                allowed_updates=None
            )

        except requests.exceptions.ReadTimeout as e:
            logger.warning(f"Polling ReadTimeout: {e!s}. Retrying in {POLL_RETRY_DELAY}s...")
            time.sleep(POLL_RETRY_DELAY)
        except requests.exceptions.ConnectTimeout as e:
            logger.warning(f"Polling ConnectTimeout: {e!s}. Retrying in {POLL_RETRY_DELAY}s...")
            time.sleep(POLL_RETRY_DELAY)
        except requests.exceptions.ConnectionError as e:
            logger.warning(f"Polling ConnectionError: {e!s}. Retrying in {POLL_CONNECTION_RETRY_DELAY}s...")
            time.sleep(POLL_CONNECTION_RETRY_DELAY)
        except requests.exceptions.RequestException as e:
            logger.warning(f"Telegram HTTP error: {e!s}. Retrying in {POLL_RETRY_DELAY}s...")
            time.sleep(POLL_RETRY_DELAY)
        except KeyboardInterrupt:
            logger.info("🛑 Bot stopped by user.")
            break
        except Exception as e:
            logger.critical(f"💥 Polling error: {e!s}. Restarting in {POLL_ERROR_RETRY_DELAY}s...", exc_info=True)
            time.sleep(POLL_ERROR_RETRY_DELAY)
        finally:
            logger.info("Polling cycle ended; watchdog loop remains active.")